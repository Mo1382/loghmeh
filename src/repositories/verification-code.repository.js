import VerificationCode from "@/models/VerificationCode";

/**
 * Apply MongoDB session only when provided.
 */
function applySession(query, session) {
  return session ? query.session(session) : query;
}

/**
 * Find the active verification code for an email and purpose.
 *
 * Only non-expired codes are considered.
 * The newest code is returned when multiple active
 * records exist.
 */
export function findActiveVerificationCode(email, purpose, session) {
  const query = VerificationCode.findOne({
    email,
    purpose,
    expiresAt: {
      $gt: new Date(),
    },
  }).sort({
    createdAt: -1,
  });

  return applySession(query, session);
}

/**
 * Create a verification code.
 *
 * The codeHash is generated by the Service layer.
 */
export function createVerificationCode(codeData, session) {
  if (session) {
    return VerificationCode.create([codeData], { session }).then(
      ([code]) => code
    );
  }

  return VerificationCode.create(codeData);
}

/**
 * Delete verification codes for a specific email
 * and purpose.
 *
 * Used before creating a new code so that the
 * previous active code is no longer usable.
 */
export function deleteVerificationCodesByEmailAndPurpose(
  email,
  purpose,
  session
) {
  const query = VerificationCode.deleteMany({
    email,
    purpose,
    expiresAt: {
      $gt: new Date(),
    },
  });

  return applySession(query, session);
}

/**
 * Replace the current verification code with a new one.
 *
 * The Service layer is responsible for generating and
 * hashing the new code.
 */
export async function replaceVerificationCode(codeData, session) {
  await deleteVerificationCodesByEmailAndPurpose(
    codeData.email,
    codeData.purpose,
    session
  );

  return createVerificationCode(codeData, session);
}

/**
 * Delete a verification code after successful use.
 *
 * This helps enforce one-time code usage.
 */
export function deleteVerificationCodeById(verificationCodeId, session) {
  const query = VerificationCode.findByIdAndDelete(verificationCodeId);

  return applySession(query, session);
}
