import { z } from "zod";

/**
 * Reusable fields
 */

const objectIdSchema = z.string().regex(/^[a-fA-F0-9]{24}$/, "Invalid ID.");

const titleSchema = z
  .string()
  .trim()
  .min(5, "Recipe title must be at least 5 characters.")
  .max(120, "Recipe title must not exceed 120 characters.");

const descriptionSchema = z
  .string()
  .trim()
  .min(30, "Description must be at least 30 characters.")
  .max(500, "Description must not exceed 500 characters.");

const originSchema = z
  .string()
  .trim()
  .max(60, "Origin must not exceed 60 characters.");

const difficultySchema = z.enum(["آسان", "متوسط", "سخت"]);

const preparationTimeSchema = z
  .number()
  .int()
  .min(1, "Preparation time must be at least 1 minute.");

const servingsSchema = z
  .number()
  .int()
  .min(1, "Serving size must be at least 1.")
  .max(100, "Serving size must not exceed 100.");

const imageSchema = z
  .string()
  .trim()
  .url("Image must be a valid URL.")
  .refine((value) => value.startsWith("https://"), "Image URL must use HTTPS.");

const caloriesSchema = z.number().min(0, "Calories cannot be negative.");

/**
 * Ingredient
 */

const ingredientSchema = z
  .object({
    name: z.string().trim().min(1, "Ingredient name is required."),

    quantity: z
      .number()
      .min(0, "Ingredient quantity cannot be negative.")
      .nullable()
      .optional(),

    unit: z.string().trim().min(1, "Ingredient unit is required."),
  })
  .strict()
  .superRefine((data, ctx) => {
    if (data.unit === "به مقدار کافی") {
      if (data.quantity != null) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message:
            'Quantity must not be provided when unit is "به مقدار کافی".',
          path: ["quantity"],
        });
      }
    } else if (data.quantity == null) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: "Ingredient quantity is required.",
        path: ["quantity"],
      });
    }
  });

/**
 * Ingredients
 */

const ingredientsSchema = z
  .array(ingredientSchema)
  .min(1, "Recipe must contain at least one ingredient.");

/**
 * Cooking step
 */

const stepSchema = z
  .object({
    order: z.number().int().min(1, "Step order must start from 1."),

    title: z.string().trim().min(1, "Step title is required."),

    description: z.string().trim().min(1, "Step description is required."),
  })
  .strict();

/**
 * Cooking steps
 */

const stepsSchema = z
  .array(stepSchema)
  .min(1, "Recipe must contain at least one cooking step.")
  .superRefine((steps, ctx) => {
    const orders = steps.map((step) => step.order);

    const expectedOrders = steps.map((_, index) => index + 1);

    const isSequential = orders.every(
      (order, index) => order === expectedOrders[index]
    );

    if (!isSequential) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: "Cooking step orders must be sequential starting from 1.",
        path: ["order"],
      });
    }
  });

/**
 * Create recipe
 *
 * authorId is obtained from the authenticated user.
 * slug is generated by the server.
 * stats and timestamps are system-managed.
 */

export const createRecipeSchema = z
  .object({
    // In UI, catgory id (instead of catgeory name) must sent when add rcipe form submitted.
    categoryId: objectIdSchema,

    title: titleSchema,

    description: descriptionSchema,

    origin: originSchema.nullable().optional(),

    difficulty: difficultySchema,

    preparationTime: preparationTimeSchema,

    defaultServings: servingsSchema,

    image: imageSchema,

    ingredients: ingredientsSchema,

    steps: stepsSchema,

    calories: caloriesSchema.nullable().optional(),
  })
  .strict();

/**
 * Update recipe
 *
 * Partial update.
 * At least one field must be provided.
 */

export const updateRecipeSchema = z
  .object({
    categoryId: objectIdSchema.optional(),

    title: titleSchema.optional(),

    description: descriptionSchema.optional(),

    origin: originSchema.nullable().optional(),

    difficulty: difficultySchema.optional(),

    preparationTime: preparationTimeSchema.optional(),

    defaultServings: servingsSchema.optional(),

    image: imageSchema.optional(),

    ingredients: ingredientsSchema.optional(),

    steps: stepsSchema.optional(),

    calories: caloriesSchema.nullable().optional(),
  })
  .strict()
  .refine((data) => Object.keys(data).length > 0, {
    message: "At least one field must be provided.",
  });
